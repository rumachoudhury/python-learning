
# Setting the Data Type

x = "Hello World"
print(type(x))



y = 20
print(type(y))


# create a list
fruits = ["apple", "banana", "orange"]
print(type(fruits))


# tuple instead, use parentheses:
fruits = ("apple", "banana", "orange")
print(type(fruits))


# A dictionary needs every item to have a key
fruits = {"fruit1":"apple", "fruit2":"banana", "fruit3":"orange"}
print(type(fruits))


# Create set
fruits = {"apple", "banana", "orange"}
print(type(fruits))

# =====================================
# []----> creates a list.
# ()----> creates a tuple.
# Set need----> values only
# Dictionary need----> key and value