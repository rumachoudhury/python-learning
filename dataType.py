
# Setting the Data Type

x = "Hello World"
print(type(x))



y = 20
print(type(y))


# create a list
fruits = ["apple", "banana", "orange"]
print(type(fruits))


# tuple instead, use parentheses:
fruits = ("apple", "banana", "orange")
print(type(fruits))

# =====================================
# []----> creates a list.
# ()-----> creates a tuple.