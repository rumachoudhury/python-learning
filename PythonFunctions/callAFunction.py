
# Calling a Function
# To call (run) a function, write the function name followed by ().

# Example
def my_function():
  print("Hello from a function")

my_function()



# =============================
# You can call the same function multiple times:

def my_function():
    print("Hello!")

my_function()
my_function()
my_function()

# Output:

# Hello!
# Hello!
# Hello!

# def my_function():  → create the function

# my_function()       → call/run the function

# def = create
# () = call/run