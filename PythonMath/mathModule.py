
# Python has a built-in module called math that provides extra mathematical functions and constants.

# Example: Square Root
import math

x = math.sqrt(64)

print(x)

# Output:

# 8.0
# Remember

# import math — imports the built-in math module.

# math.sqrt(64) — calculates the square root of 64.

# The square root of 64 is 8, and Python returns it as 8.0.

# You don't need to install anything. The math module comes with Python.