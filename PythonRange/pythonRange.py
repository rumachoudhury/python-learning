

# Creating Ranges

# The range() function can take 1, 2, or 3 arguments:

# range(start, stop, step)

# One Argument
for x in range(5):
    print(x)


# Output:

# 0
# 1
# 2
# 3
# 4

# With one argument:

# range(5)

# means start at 0, stop before 5.

# =================================
# 2. Two Arguments
for x in range(2, 6):
    print(x)

# Output:

# 2
# 3
# 4
# 5
# range(2, 6)
# 2 → start
# 6 → stop (not included)