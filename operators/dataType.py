
# Setting the Data Type

x = "Hello World"
print(type(x))



y = 20
print(type(y))


# create a list
fruits = ["apple", "banana", "orange"]
print(type(fruits))


# tuple instead, use parentheses:
fruits = ("apple", "banana", "orange")
print(type(fruits))


# A dictionary(dict) needs every item to have a key
fruits = {"fruit1":"apple", "fruit2":"banana", "fruit3":"orange"}
print(type(fruits))

student = {"name" : "John", "age" : 30}
print(type(student))


# Create set
fruits = {"apple", "banana", "orange"}
print(type(fruits))

# =====================================
# []----> creates a list.
# ()----> creates a tuple.
# Set need----> values only
# Dictionary(dict) need----> key and value